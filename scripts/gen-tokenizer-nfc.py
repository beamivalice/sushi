#!/usr/bin/env python3
"""Generate the NFC tables (`src/tokenizer_nfc_tables.zig`) and their oracle cases (`src/fixtures/nfc_cases.json`)
with Python 3.14 / Unicode 16.0, the version `gen-tokenizer-unicode.py` reads.
"""
import json
import random
import unicodedata as u
from pathlib import Path

assert u.unidata_version == '16.0.0', u.unidata_version
root = Path(__file__).resolve().parents[1]
SBASE, SCOUNT = 0xAC00, 11172


def canonical(cp):
    d = u.decomposition(chr(cp))
    if not d or d.startswith('<'):
        return None
    return [int(x, 16) for x in d.split()]


ccc = [(cp, u.combining(chr(cp))) for cp in range(0x110000) if u.combining(chr(cp))]
decomp = []
compose = []
for cp in range(0x110000):
    if SBASE <= cp < SBASE + SCOUNT:
        continue
    d = canonical(cp)
    if d is None:
        continue
    full = [ord(c) for c in u.normalize('NFD', chr(cp))]
    decomp.append((cp, full))
    # A primary composite: a pair decomposition that NFC recomposes (not excluded, not a non-starter decomposition).
    if len(d) == 2 and u.normalize('NFC', chr(d[0]) + chr(d[1])) == chr(cp):
        compose.append((d[0], d[1], cp))
compose.sort()

flat = []
rows = []
for cp, full in decomp:
    rows.append(f'    .{{ .cp = 0x{cp:x}, .at = {len(flat)}, .len = {len(full)} }},\n')
    flat.extend(full)

text = ['// Generated by scripts/gen-tokenizer-nfc.py using Unicode 16.0.0.\n',
        '// Canonical combining classes, full canonical decompositions and primary composites, for NFC.\n',
        'pub const Ccc = struct { cp: u21, class: u8 };\n',
        'pub const Decomp = struct { cp: u21, at: u16, len: u8 };\n',
        'pub const Pair = struct { first: u21, second: u21, composite: u21 };\n',
        'pub const ccc = [_]Ccc{\n']
text += [f'    .{{ .cp = 0x{cp:x}, .class = {c} }},\n' for cp, c in ccc]
text += ['};\n', 'pub const decomp = [_]Decomp{\n'] + rows + ['};\n', 'pub const decomp_cps = [_]u21{\n']
text += ['    ' + ', '.join(f'0x{x:x}' for x in flat[i:i + 12]) + ',\n' for i in range(0, len(flat), 12)]
text += ['};\n', 'pub const pairs = [_]Pair{\n']
text += [f'    .{{ .first = 0x{a:x}, .second = 0x{b:x}, .composite = 0x{c:x} }},\n' for a, b, c in compose]
text += ['};\n']
(root / 'src/tokenizer_nfc_tables.zig').write_text(''.join(text))

# Oracle cases: every canonical decomposition, Hangul jamo runs, and marks in shuffled orders on varied bases.
rng = random.Random(16)
cases = [u.normalize('NFD', chr(cp)) for cp, _ in decomp]
cases += [chr(0x1100 + rng.randrange(19)) + chr(0x1161 + rng.randrange(21)) + (chr(0x11A8 + rng.randrange(27)) if rng.random() < .5 else '') for _ in range(64)]
marks = [cp for cp, _ in ccc if cp < 0x10000]
bases = 'aeiouAEIOUcnsyzKLOU\u0391\u03b1\u0410\u0430\u05d0\u0627\u0915\u3042\uac00'
for _ in range(512):
    s = rng.choice(bases) + ''.join(chr(rng.choice(marks)) for _ in range(rng.randrange(1, 5)))
    cases.append(s if rng.random() < .5 else u.normalize('NFD', s))
cases = sorted(set(c for c in cases if c != u.normalize('NFC', c)))
oracle = [[c, u.normalize('NFC', c)] for c in cases]
(root / 'src/fixtures/nfc_cases.json').write_text(json.dumps(oracle, ensure_ascii=False, separators=(',', ':')) + '\n')
